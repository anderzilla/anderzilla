param(
  [string]$CodeRoot = 'Z:/AnderZilla',
  [switch]$InstallUserSkills
)
$ErrorActionPreference = 'Stop'
$docsRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$targetRoot = (Resolve-Path -LiteralPath $CodeRoot).Path
$branchName = (& git -C $docsRoot branch --show-current).Trim()
if ($branchName -ne 'codex/anderzilla-docs') { throw 'Use o worktree documental AnderZilla.' }
$originUrl = (& git -C $targetRoot remote get-url origin).Trim()
if ($originUrl -notmatch 'github.com[:/]anderzilla/AnderZilla(?:\.git)?$') { throw 'Destino não é o repositório AnderZilla esperado.' }
$pythonPath = (Get-Command python -ErrorAction Stop).Source
$ragPath = Join-Path $docsRoot 'ai/rag/rag.py'
if (-not (Test-Path -LiteralPath $ragPath)) { throw 'RAG não encontrado.' }
function Write-OwnedFile([string]$Path, [string]$Content) {
  if (Test-Path -LiteralPath $Path) {
    $oldContent = Get-Content -Raw -LiteralPath $Path
    if ($oldContent -ne $Content) { throw "Arquivo existente difere: $Path. Revise sem sobrescrever configuração alheia." }
  } else {
    New-Item -ItemType Directory -Force (Split-Path $Path) | Out-Null
    [IO.File]::WriteAllText($Path, $Content, [Text.UTF8Encoding]::new($false))
  }
}
function Add-OwnedJunction([string]$Path, [string]$Target) {
  if (Test-Path -LiteralPath $Path) {
    $item = Get-Item -LiteralPath $Path
    if ($item.LinkType -ne 'Junction' -or [IO.Path]::GetFullPath($item.Target) -ne [IO.Path]::GetFullPath($Target)) { throw "Destino existente não é junction esperada: $Path" }
  } else {
    New-Item -ItemType Directory -Force (Split-Path $Path) | Out-Null
    New-Item -ItemType Junction -Path $Path -Target $Target | Out-Null
  }
}
$tomlPython = $pythonPath.Replace('\','/')
$tomlRag = $ragPath.Replace('\','/')
$codexConfig = @"
# Generated by AnderZilla docs ai/bootstrap.ps1. Local only.
[mcp_servers.anderzilla_knowledge]
command = "$tomlPython"
args = ["$tomlRag", "serve"]

[mcp_servers.microsoft_learn]
url = "https://learn.microsoft.com/api/mcp"
"@
$claudeConfig = @{mcpServers=@{
  'anderzilla-knowledge'=@{type='stdio';command=$pythonPath;args=@($ragPath,'serve')}
  'microsoft-learn'=@{type='http';url='https://learn.microsoft.com/api/mcp'}
}} | ConvertTo-Json -Depth 6
Write-OwnedFile (Join-Path $targetRoot '.codex/config.toml') $codexConfig
Write-OwnedFile (Join-Path $targetRoot '.mcp.json') $claudeConfig
Add-OwnedJunction (Join-Path $targetRoot '.agents/skills') (Join-Path $docsRoot 'ai/skills')
Add-OwnedJunction (Join-Path $targetRoot '.claude/agents') (Join-Path $docsRoot 'ai/agents')
Add-OwnedJunction (Join-Path $targetRoot '.claude/skills') (Join-Path $docsRoot 'ai/skills')
if ($InstallUserSkills) {
  $userSkills = Join-Path $env:USERPROFILE '.codex/skills'
  Get-ChildItem (Join-Path $docsRoot 'ai/skills') -Directory | ForEach-Object {
    Add-OwnedJunction (Join-Path $userSkills $_.Name) $_.FullName
  }
}
Write-Output 'Configurações locais e junctions criadas. Reabra a sessão para descobrir skills/MCP. Nenhum segredo ou recurso cloud foi criado.'
